def zipped(
    files: Mapping[str, bytes | str], nested: Mapping[str, Mapping[str, bytes | str]] | None = None
) -> bytes:
    """Zip of `files`; `nested`: archives inside the archive, by name."""
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in files.items():
            archive.writestr(name, data.encode() if isinstance(data, str) else data)
        for name, inner in (nested or {}).items():
            archive.writestr(name, zipped(inner))
    return out.getvalue()


