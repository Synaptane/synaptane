def confluence_page(
    title: str, crumbs: list[tuple[str, str]], body: str, sections: str = "", space: str = "Ops"
) -> str:
    """A page as Confluence exports it in HTML."""
    trail = "".join(f'<li><span><a href="{href}">{text}</a></span></li>' for href, text in crumbs)
    return f"""<!DOCTYPE html>
<html><head><title>{space} : {title}</title>
<link rel="stylesheet" href="styles/site.css" type="text/css"><script>alert(1)</script></head>
<body class="theme-default aui-theme-default"><div id="page"><div id="main" class="aui-page-panel">
<div id="main-header"><div id="breadcrumb-section"><ol id="breadcrumbs">{trail}</ol></div>
<h1 id="title-heading" class="pagetitle"><span id="title-text"> {space} : {title} </span></h1></div>
<div id="content" class="view">
<div class="page-metadata">Created by <span class='author'> Ada Lovelace</span>,
 last modified on Oct 03, 2026</div>
<div id="main-content" class="wiki-content group">{body}</div>
{sections}
</div></div>
<div id="footer" role="contentinfo"><section class="footer-body">
<p>Document generated by Confluence on Oct 03, 2026 10:00</p></section></div>
</div></body></html>"""


