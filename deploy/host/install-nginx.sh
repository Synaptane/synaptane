#!/usr/bin/env bash
# Host nginx site and Let's Encrypt certificate for Synaptane (Debian, Ubuntu).
#
#   sudo deploy/host/install-nginx.sh brain.example.com
#
# 1. HTTP-only site (ACME challenge and redirect), if the certificate does not exist yet;
# 2. certificate dedicated to the domain (certbot in webroot mode, which leaves other sites alone);
# 3. full site: deploy/nginx/host-site.conf, with the domain, the port and the challenge
#    folder replaced. HTTP → HTTPS, HSTS, `server_tokens off`.
# Safe to run again: it is also the way to apply a new version of the site.
#
# Settings through environment variables:
#   APP_PORT  Synaptane port on 127.0.0.1 (default 8000, as in .env)
#   WEBROOT   ACME challenge folder (default /var/www/letsencrypt)
#   LETSENCRYPT_EMAIL  Let's Encrypt account address (expiry warnings)
set -euo pipefail

domain="${1:-${DOMAIN:-}}"
port="${APP_PORT:-8000}"
webroot="${WEBROOT:-/var/www/letsencrypt}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
template="$here/../nginx/host-site.conf"
site="/etc/nginx/sites-available/$domain"
cert="/etc/letsencrypt/live/$domain"

die() { echo "$*" >&2; exit 1; }

[[ "$domain" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ && "$domain" == *.* ]] \
  || die "Usage: sudo $0 <domain>   (for example brain.example.com)"
[[ "$port" =~ ^[0-9]+$ ]] || die "APP_PORT: a port number."
[[ "$webroot" =~ ^/[A-Za-z0-9/._-]+$ ]] || die "WEBROOT: a simple absolute path."
[ "$(id -u)" = 0 ] || die "Run with sudo."
[ -f "$template" ] || die "Template not found: $template"
command -v nginx >/dev/null || die "nginx is not installed (apt install nginx)."
command -v certbot >/dev/null || die "certbot is not installed (apt install certbot)."

if ! getent ahostsv4 "$domain" >/dev/null; then
  die "$domain does not resolve yet: add the DNS record, then run again."
fi

# The template without its header (instructions), values replaced.
render() {
  echo "# Synaptane, $domain: generated by deploy/host/install-nginx.sh from"
  echo "# deploy/nginx/host-site.conf. Edit the template and run the script again."
  sed -e '1,/^$/d' \
      -e "s/brain\.example\.com/$domain/g" \
      -e "s#127\.0\.0\.1:8000#127.0.0.1:$port#g" \
      -e "s#/var/www/letsencrypt#$webroot#g" \
      "$template"
}

reload() { nginx -t && systemctl reload nginx; }

install -d -m 755 "$webroot"

if [ ! -f "$cert/fullchain.pem" ]; then
  echo "== 1. HTTP site (ACME challenge)"
  render | sed -n '1,/^# --- end of HTTP block/p' > "$site"
  ln -sf "$site" "/etc/nginx/sites-enabled/$domain"
  reload

  echo "== 2. Certificate"
  # Let's Encrypt account: created with the server's first certificate (these options have no
  # effect if it already exists). LETSENCRYPT_EMAIL receives the expiry warnings.
  if [ -n "${LETSENCRYPT_EMAIL:-}" ]; then
    account=(--email "$LETSENCRYPT_EMAIL")
  else
    account=(--register-unsafely-without-email)
  fi
  certbot certonly --webroot -w "$webroot" -d "$domain" --non-interactive --agree-tos \
    "${account[@]}" --deploy-hook "systemctl reload nginx"
else
  echo "== 1 and 2. Certificate already present: $cert"
fi

echo "== 3. HTTPS site"
render > "$site"
ln -sf "$site" "/etc/nginx/sites-enabled/$domain"
reload

echo
echo "Done: https://$domain"
curl -s -o /dev/null -w "readyz through nginx: %{http_code}\n" \
  --resolve "$domain:443:127.0.0.1" "https://$domain/readyz" || true
